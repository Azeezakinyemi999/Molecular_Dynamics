    import matplotlib.pyplot as plt
    import matplotlib.cm as cm

    if summary.empty:
        print('No data to plot.')
        return

    structs  = summary['struct'].unique()
    n_h_list = sorted(summary['n_h'].unique())
    cmap      = cm.get_cmap('viridis', len(n_h_list))
