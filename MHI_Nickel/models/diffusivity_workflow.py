def generate_orchestrator_sh(
    orch_job_name,
    orch_partition,
    orch_cpus_per_task,
    orch_mem,
    orch_time,
    orch_openmpi_ver,
    orch_cuda_version,
    orch_conda_env,
    orch_ld_paths,
    work_dir,
    out_py,
    out_sh: str,
) -> str:
    """Write diffusivity_run.sh and chmod +x it. Returns the output path."""

    orch_time_line = f'#SBATCH --time={orch_time}' if orch_time else ''
    _ld_lines = ('\n        ').join(
        f'export LD_LIBRARY_PATH={p}:$LD_LIBRARY_PATH'
        for p in orch_ld_paths
    )
    orch_output = f'{orch_job_name}_%j.out'

    content = textwrap.dedent(f"""\
        #!/bin/bash
        #SBATCH --job-name={orch_job_name}
        #SBATCH --partition={orch_partition}
        #SBATCH --ntasks=1
        #SBATCH --cpus-per-task={orch_cpus_per_task}
        #SBATCH --mem={orch_mem}
        #SBATCH --output={orch_output}
        {orch_time_line}

        module load OpenMPI/{orch_openmpi_ver}
        module load cuda/{orch_cuda_version}
        source ~/miniforge3/etc/profile.d/conda.sh
        conda activate {orch_conda_env}
        {_ld_lines}

        cd {work_dir}

        echo "Node: $(hostname)  Start: $(date)"
        python {out_py}
        echo "End: $(date)"
    """)

    os.makedirs(os.path.dirname(os.path.abspath(out_sh)), exist_ok=True)
    with open(out_sh, 'w') as fh:
        fh.write(content)
    os.chmod(out_sh, 0o755)
    return out_sh


