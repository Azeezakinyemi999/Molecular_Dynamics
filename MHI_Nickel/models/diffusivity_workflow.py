    if arr_df is None or arr_df.empty:
        print('Run plot_Ea_vs_nH first to compute arr_df.')
        return

    T_fit     = np.linspace(min(temperatures) - 20, max(temperatures) + 20, 200)
    inv_T_fit = 1000.0 / T_fit

